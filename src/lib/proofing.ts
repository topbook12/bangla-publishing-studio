export const CUSTOM_DICT_KEY = 'bwp-custom-dict';

/** ব্যবহারকারীর কাস্টম অভিধান (localStorage); SSR-নিরাপদ */
export function getCustomDict(): Set<string> {
  try {
    if (typeof window === 'undefined') return new Set();
    const raw = window.localStorage.getItem(CUSTOM_DICT_KEY);
    if (!raw) return new Set();
    const arr: unknown = JSON.parse(raw);
    if (!Array.isArray(arr)) return new Set();
    return new Set(arr.filter((x): x is string => typeof x === 'string').map(normalizeBanglaWord));
  } catch {
    return new Set();
  }
}

/** কাস্টম অভিধানে শব্দ যোগ */
export function addToCustomDict(word: string): void {
  try {
    if (typeof window === 'undefined') return;
    const dict = getCustomDict();
    dict.add(normalizeBanglaWord(word));
    window.localStorage.setItem(CUSTOM_DICT_KEY, JSON.stringify(Array.from(dict)));
  } catch {
    // নীরবে উপেক্ষা
  }
}

/** কাস্টম অভিধান থেকে শব্দ মুছুন */
export function removeFromCustomDict(word: string): void {
  try {
    if (typeof window === 'undefined') return;
    const dict = getCustomDict();
    dict.delete(normalizeBanglaWord(word));
    window.localStorage.setItem(CUSTOM_DICT_KEY, JSON.stringify(Array.from(dict)));
  } catch {
    // নীরবে উপেক্ষা
  }
}

/** বাংলা ও ল্যাটিন শব্দ টোকেন */
export function tokenizeBangla(text: string): string[] {
  return text.match(/[\u0980-\u09FF]+|[A-Za-z][A-Za-z'-]*/g) ?? [];
}

/** শব্দটি পরিচিত কি না (সাধারণ + কাস্টম অভিধান) */
export function isWordKnown(word: string): boolean {
  const w = normalizeBanglaWord(word);
  if (w.length <= 1) return true;
  if (BANGLA_COMMON_WORDS.has(w)) return true;
  if (ENGLISH_COMMON_WORDS.has(w.toLowerCase())) return true;
  // বাংলা ডিজিট বা ল্যাটিন ডিজিটযুক্ত টোকেন বাদ
  if (/[০-৯0-9]/.test(w)) return true;
  return getCustomDict().has(w);
}

export interface SuspiciousWord {
  word: string;
  count: number;
  /** পুরো টেক্সটে প্রথম আবির্ভাবের ইনডেক্স */
  firstIndex: number;
}

/**
 * টেক্সট স্ক্যান করে অভিধানে না-থাকা শব্দগুলো সংখ্যা অনুযায়ী সাজিয়ে দেয়।
 * maxResults দিয়ে সীমাবদ্ধ করা যায় (ডিফল্ট ৩০০)।
 */
export function scanText(
  text: string,
  opts?: { maxResults?: number },
): SuspiciousWord[] {
  const maxResults = opts?.maxResults ?? 300;
  const tokens = tokenizeBangla(text);
  const order = new Map<string, number>();
  const counts = new Map<string, number>();
  let index = 0;
  for (const token of tokens) {
    const normalized = normalizeBanglaWord(token);
    if (!order.has(normalized)) order.set(normalized, index);
    index += token.length + 1;
    if (isWordKnown(normalized)) continue;
    counts.set(normalized, (counts.get(normalized) ?? 0) + 1);
  }
  const results: SuspiciousWord[] = [];
  for (const [word, count] of counts) {
    results.push({ word, count, firstIndex: order.get(word) ?? 0 });
  }
  results.sort((a, b) => b.count - a.count || a.firstIndex - b.firstIndex);
  return results.slice(0, maxResults);
}
