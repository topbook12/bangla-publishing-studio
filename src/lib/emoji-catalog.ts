export const EMOJI_COUNT = ALL_EMOJIS.length;

const EMOJI_BY_CHAR = new Map<string, EmojiEntry>(ALL_EMOJIS.map((e) => [e.char, e]));

export function getEmoji(char: string): EmojiEntry | undefined {
  return EMOJI_BY_CHAR.get(char);
}

/** ইমোজি সার্চ — নাম+কীওয়ার্ডে ম্যাচ (কেস-অসংবেদনশীল) */
export function searchEmojis(query: string): { categories: EmojiCategory[]; total: number } {
  const q = query.trim().toLowerCase();
  if (!q) return { categories: EMOJI_CATEGORIES, total: EMOJI_COUNT };
  const categories: EmojiCategory[] = [];
  let total = 0;
  for (const c of EMOJI_CATEGORIES) {
    const emojis = c.emojis.filter((e) => e.name.toLowerCase().includes(q) || e.kw.includes(q));
    if (emojis.length) {
      categories.push({ ...c, emojis });
      total += emojis.length;
    }
  }
  return { categories, total };
}
